package com.example.register.repository;

import com.example.register.domain.User;
import java.sql.*;
import java.util.Optional;

public class JdbcUserRepository implements UserRepository {
    private final String jdbcUrl;

    public JdbcUserRepository(String jdbcUrl) {
        this.jdbcUrl = jdbcUrl;
        initialiseSchema();
    }

    private Connection connection() throws SQLException {
        return DriverManager.getConnection(jdbcUrl, "sa", "");
    }

    private void initialiseSchema() {
        String sql = "CREATE TABLE IF NOT EXISTS users (" +
                "id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY," +
                "full_name VARCHAR(150) NOT NULL," +
                "email VARCHAR(255) NOT NULL UNIQUE," +
                "password_hash VARCHAR(255) NOT NULL," +
                "created_at TIMESTAMP NOT NULL)";
        try (Connection c = connection(); Statement s = c.createStatement()) {
            s.execute(sql);
        } catch (SQLException e) {
            throw new IllegalStateException("Could not initialise database schema", e);
        }
    }

    @Override
    public boolean existsByEmail(String email) {
        String sql = "SELECT 1 FROM users WHERE LOWER(email) = LOWER(?)";
        try (Connection c = connection(); PreparedStatement s = c.prepareStatement(sql)) {
            s.setString(1, email);
            try (ResultSet r = s.executeQuery()) {
                return r.next();
            }
        } catch (SQLException e) {
            throw new IllegalStateException("Could not check email", e);
        }
    }

    @Override
    public User save(User user) {
        String sql = "INSERT INTO users(full_name, email, password_hash, created_at) VALUES (?, ?, ?, ?)";
        try (Connection c = connection();
             PreparedStatement s = c.prepareStatement(sql, Statement.RETURN_GENERATED_KEYS)) {
            s.setString(1, user.fullName());
            s.setString(2, user.email());
            s.setString(3, user.passwordHash());
            s.setTimestamp(4, Timestamp.valueOf(user.createdAt()));
            s.executeUpdate();
            try (ResultSet keys = s.getGeneratedKeys()) {
                if (keys.next()) {
                    return new User(keys.getLong(1), user.fullName(), user.email(),
                            user.passwordHash(), user.createdAt());
                }
            }
            throw new IllegalStateException("No generated ID returned");
        } catch (SQLException e) {
            throw new IllegalStateException("Could not save user", e);
        }
    }

    @Override
    public Optional<User> findByEmail(String email) {
        String sql = "SELECT id, full_name, email, password_hash, created_at FROM users WHERE LOWER(email) = LOWER(?)";
        try (Connection c = connection(); PreparedStatement s = c.prepareStatement(sql)) {
            s.setString(1, email);
            try (ResultSet r = s.executeQuery()) {
                if (!r.next()) return Optional.empty();
                return Optional.of(new User(r.getLong("id"), r.getString("full_name"),
                        r.getString("email"), r.getString("password_hash"),
                        r.getTimestamp("created_at").toLocalDateTime()));
            }
        } catch (SQLException e) {
            throw new IllegalStateException("Could not find user", e);
        }
    }
}